import std/[algorithm, json, strutils]

type
  Operation* = object
    operationId*: string
    httpMethod*: string
    path*: string
    tag*: string
    pathParams*: seq[string]
    hasBody*: bool
    isWebSocket*: bool

proc collectOperations*(doc: JsonNode, source: string): seq[Operation] =
  if not doc.hasKey("paths"):
    raise newException(ValueError, source & ": missing paths")
  var paths: seq[string] = @[]
  for path in doc["paths"].keys:
    paths.add(path)
  paths.sort()
  for path in paths:
    let item = doc["paths"][path]
    for verb in ["get", "post", "put", "patch", "delete"]:
      if not item.hasKey(verb):
        continue
      let node = item[verb]
      if not node.hasKey("operationId"):
        raise newException(ValueError, source & ": " & verb & " " & path & " has no operationId")
      var params: seq[string] = @[]
      if node.hasKey("parameters"):
        for parameter in node["parameters"]:
          if parameter["in"].getStr() == "path":
            params.add(parameter["name"].getStr())
      result.add(Operation(
        operationId: node["operationId"].getStr(),
        httpMethod: verb.toUpperAscii(),
        path: path,
        tag: if node.hasKey("tags") and node["tags"].len > 0: node["tags"][0].getStr() else: "",
        pathParams: params,
        hasBody: node.hasKey("requestBody"),
        isWebSocket: node.hasKey("x-websocket"),
      ))

proc sortOperations*(operations: var seq[Operation]) =
  operations.sort(proc(a, b: Operation): int =
    result = cmp(a.path, b.path)
    if result == 0:
      result = cmp(a.httpMethod, b.httpMethod))

proc nimString(value: string): string =
  result = "\""
  for c in value:
    case c
    of '\\': result.add("\\\\")
    of '"': result.add("\\\"")
    of '\n': result.add("\\n")
    else: result.add(c)
  result.add('"')

proc renderNim*(operations: seq[Operation]): string =
  result = "# Generated by tools/contract-gen. Do not edit.\n\n"
  result.add("type\n  RouteSpec* = object\n")
  result.add("    operationId*: string\n    httpMethod*: string\n    path*: string\n")
  result.add("    tag*: string\n    pathParams*: string\n")
  result.add("    hasBody*: bool\n    isWebSocket*: bool\n\n")
  result.add("const routes* = [\n")
  for operation in operations:
    result.add("  RouteSpec(\n")
    result.add("    operationId: " & nimString(operation.operationId) & ",\n")
    result.add("    httpMethod: " & nimString(operation.httpMethod) & ",\n")
    result.add("    path: " & nimString(operation.path) & ",\n")
    result.add("    tag: " & nimString(operation.tag) & ",\n")
    result.add("    pathParams: " & nimString(operation.pathParams.join(",")) & ",\n")
    result.add("    hasBody: " & (if operation.hasBody: "true" else: "false") & ",\n")
    result.add("    isWebSocket: " & (if operation.isWebSocket: "true" else: "false") & ",\n")
    result.add("  ),\n")
  result.add("]\n\n")
  result.add("const routeCount* = " & $operations.len & "\n")
  result.add("""

