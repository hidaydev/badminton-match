import std/[algorithm, json, strutils]

type
  Operation* = object
    operationId*: string
    httpMethod*: string
    path*: string
    tag*: string
    pathParams*: seq[string]
    queryParams*: seq[string]
    requestKeys*: seq[string]
    hasBody*: bool
    isWebSocket*: bool

proc resolveSchema(doc, schema: JsonNode): JsonNode =
  ## One level of local `$ref` is all the specs use; a chain is followed until
  ## it leaves the document, which then yields no keys rather than looping.
  if schema.isNil:
    return newJObject()
  result = schema
  var seen = 0
  while result.kind == JObject and result.hasKey("$ref") and seen < 8:
    let reference = result["$ref"].getStr()
    if not reference.startsWith("#/"):
      return newJObject()
    var node = doc
    for part in reference[2 .. ^1].split('/'):
      if node.kind != JObject or not node.hasKey(part):
        return newJObject()
      node = node[part]
    result = node
    inc seen

proc requestKeysOf(doc, operation: JsonNode): seq[string] =
  ## The keys a caller may send: the request body's object properties. A body
  ## with no schema properties declares no key, which is the honest answer for
  ## an endpoint the contract has not described yet.
  if not operation.hasKey("requestBody"):
    return @[]
  let body = operation["requestBody"]
  if body.kind != JObject:
    return @[]
  let content = body{"content"}
  if content.isNil or content.kind != JObject or
      not content.hasKey("application/json"):
    return @[]
  let media = content["application/json"]
  let schema = resolveSchema(doc, media{"schema"})
  if schema.isNil or schema.kind != JObject or not schema.hasKey("properties"):
    return @[]
  for name in schema["properties"].keys:
    result.add name
  result.sort()

proc collectOperations*(doc: JsonNode, source: string): seq[Operation] =
  if not doc.hasKey("paths"):
    raise newException(ValueError, source & ": missing paths")
  var paths: seq[string] = @[]
  for path in doc["paths"].keys:
    paths.add(path)
  paths.sort()
  for path in paths:
    let item = doc["paths"][path]
    for verb in ["get", "post", "put", "patch", "delete"]:
      if not item.hasKey(verb):
        continue
      let node = item[verb]
      if not node.hasKey("operationId"):
        raise newException(ValueError, source & ": " & verb & " " & path & " has no operationId")
      var params: seq[string] = @[]
      var queries: seq[string] = @[]
      if node.hasKey("parameters"):
        for parameter in node["parameters"]:
          if parameter["in"].getStr() == "path":
            params.add(parameter["name"].getStr())
          elif parameter["in"].getStr() == "query":
            queries.add(parameter["name"].getStr())
      result.add(Operation(
        operationId: node["operationId"].getStr(),
        httpMethod: verb.toUpperAscii(),
        path: path,
        tag: if node.hasKey("tags") and node["tags"].len > 0: node["tags"][0].getStr() else: "",
        pathParams: params,
        queryParams: queries,
        requestKeys: requestKeysOf(doc, node),
        hasBody: node.hasKey("requestBody"),
        isWebSocket: node.hasKey("x-websocket"),
      ))

proc sortOperations*(operations: var seq[Operation]) =
  operations.sort(proc(a, b: Operation): int =
    result = cmp(a.path, b.path)
    if result == 0:
      result = cmp(a.httpMethod, b.httpMethod))

proc nimString(value: string): string =
  result = "\""
  for c in value:
    case c
    of '\\': result.add("\\\\")
    of '"': result.add("\\\"")
    of '\n': result.add("\\n")
    else: result.add(c)
  result.add('"')

proc renderNim*(operations: seq[Operation]): string =
  result = "# Generated by tools/contract-gen. Do not edit.\n\n"
  result.add("type\n  RouteSpec* = object\n")
  result.add("    operationId*: string\n    httpMethod*: string\n    path*: string\n")
  result.add("    tag*: string\n    pathParams*: string\n    queryParams*: string\n")
  result.add("    requestKeys*: string\n")
  result.add("    hasBody*: bool\n    isWebSocket*: bool\n\n")
  result.add("const routes* = [\n")
  for operation in operations:
    result.add("  RouteSpec(\n")
    result.add("    operationId: " & nimString(operation.operationId) & ",\n")
    result.add("    httpMethod: " & nimString(operation.httpMethod) & ",\n")
    result.add("    path: " & nimString(operation.path) & ",\n")
    result.add("    tag: " & nimString(operation.tag) & ",\n")
    result.add("    pathParams: " & nimString(operation.pathParams.join(",")) & ",\n")
    result.add("    queryParams: " & nimString(operation.queryParams.join(",")) & ",\n")
    result.add("    requestKeys: " & nimString(operation.requestKeys.join(",")) & ",\n")
    result.add("    hasBody: " & (if operation.hasBody: "true" else: "false") & ",\n")
    result.add("    isWebSocket: " & (if operation.isWebSocket: "true" else: "false") & ",\n")
    result.add("  ),\n")
  result.add("]\n\n")
  result.add("const routeCount* = " & $operations.len & "\n")
  result.add("""

import std/macros

macro verifyHandlers*(names: static[openArray[string]]): untyped =
  ## Fails compilation when a contract operation has no registered handler.
  for route in routes:
    var found = false
    for name in names:
      if name == route.operationId:
        found = true
    if not found:
      error("missing handler for contract operation: " & route.operationId)
  result = newEmptyNode()

proc routeIndex*(operationId: string): int =
  for index, route in routes:
    if route.operationId == operationId:
      return index
  -1
""")
