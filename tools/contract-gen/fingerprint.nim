## Contract fingerprint: a deterministic record of the specs and the generated
## outputs. `tools/contract-gen/gen.nim` writes it and `check.nim` verifies it, so
## a spec edit cannot reach `main` without a visible fingerprint change.

import std/[algorithm, strutils]

import sha256

const
  corePath* = "packages/contracts/openapi/core.yaml"
  communityPath* = "packages/contracts/openapi/community.yaml"
  mergedPath* = "packages/contracts/openapi/api.yaml"
  nimPath* = "apps/api/src/routes_gen.nim"
  tsPath* = "packages/web-client/src/api.ts"
  fingerprintPath* = "packages/contracts/openapi/CONTRACT.sha256"

  fingerprintHeader = """# Majadu contract fingerprint. Generated by tools/contract-gen; do not edit.
#
# Every entry below is verified by ./task contract-check. Editing either spec
# requires regenerating this file in the same commit, so the contract change is
# visible in review. Procedure: packages/contracts/openapi/README.md.
format 1
"""

type
  Entry* = object
    kind*: string
    path*: string
    digest*: string

proc entry(kind, path, source: string): Entry =
  Entry(kind: kind, path: path, digest: sha256Hex(source))

proc sortedByPath(entries: seq[Entry]): seq[Entry] =
  result = entries
  result.sort(proc(a, b: Entry): int = cmp(a.path, b.path))

proc renderFingerprint*(operations: int, coreSource, communitySource,
                        mergedSource, nimSource, tsSource: string): string =
  ## Deterministic text: header, operation count, then one digest per file.
  ## Spec entries come first, each group sorted by path.
  let specs = sortedByPath(@[
    entry("spec", corePath, coreSource),
    entry("spec", communityPath, communitySource)])
  let generated = sortedByPath(@[
    entry("generated", mergedPath, mergedSource),
    entry("generated", nimPath, nimSource),
    entry("generated", tsPath, tsSource)])
  result = fingerprintHeader
  result.add "operations " & $operations & "\n"
  for group in [specs, generated]:
    for item in group:
      result.add item.kind & " " & item.path & " " & item.digest & "\n"

proc parseFingerprint*(content: string): seq[Entry] =
  ## Reads a fingerprint file back into entries. Lines that do not carry a path
  ## and a digest are ignored, so a hand-edited file fails comparison instead of
  ## crashing the gate.
  for rawLine in content.splitLines:
    let line = rawLine.strip()
    if line.len == 0 or line.startsWith("#") or line.startsWith("format "):
      continue
    let parts = line.splitWhitespace()
    if parts.len < 3:
      continue
    let digest = parts[^1]
    let body = line[parts[0].len .. ^1].strip()
    let path = body[0 ..< max(0, body.len - digest.len)].strip()
    if path.len == 0:
      continue
    result.add Entry(kind: parts[0], path: path, digest: digest)
