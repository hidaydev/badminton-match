import std/[algorithm, json, sequtils, strutils]
import emit_nim

proc tsString(value: string): string =
  result = "\""
  for c in value:
    case c
    of '\\': result.add("\\\\")
    of '"': result.add("\\\"")
    of '\n': result.add("\\n")
    else: result.add(c)
  result.add('"')

proc tsType(node: JsonNode): string =
  ## The subset the specs use, spelled out so an unsupported shape fails the
  ## gate instead of becoming `any` in the client.
  if node.isNil:
    return "unknown"
  if node.hasKey("$ref"):
    return node["$ref"].getStr().split('/')[^1]
  if node.hasKey("enum"):
    return node["enum"].mapIt(tsString(it.getStr())).join(" | ")
  let declared =
    if node.hasKey("type"):
      if node["type"].kind == JArray:
        node["type"].getElems.mapIt(it.getStr())
      else:
        @[node["type"].getStr()]
    else:
      @[]
  var types: seq[string] = @[]
  for kind in declared:
    case kind
    of "string": types.add "string"
    of "integer", "number": types.add "number"
    of "boolean": types.add "boolean"
    of "null": types.add "null"
    of "array":
      let item = if node.hasKey("items"): tsType(node["items"]) else: "unknown"
      types.add "Array<" & item & ">"
    of "object":
      if node.hasKey("properties") or not node.hasKey("additionalProperties"):
        types.add "Record<string, unknown>"
      else:
        types.add "Record<string, " & tsType(node["additionalProperties"]) & ">"
    else:
      types.add "unknown"
  if types.len == 0:
    return "unknown"
  types.join(" | ")

proc renderTsTypes(schemas: JsonNode): string =
  ## One interface per component schema, sorted by name. A property that is not
  ## required is optional and unioned with undefined by the compiler, which is
  ## what the handwritten response types said in prose.
  if schemas.isNil or schemas.kind != JObject:
    return ""
  var names = toSeq(schemas.keys)
  names.sort()
  for name in names:
    let schema = schemas[name]
    result.add "export interface " & name & " {\n"
    let required =
      if schema.hasKey("required"):
        schema["required"].getElems.mapIt(it.getStr())
      else:
        newSeq[string]()
    if schema.hasKey("properties"):
      for property in schema["properties"].keys:
        let optional = if property in required: "" else: "?"
        result.add "  " & property & optional & ": " & tsType(schema["properties"][property]) & ";\n"
    if schema.hasKey("additionalProperties"):
      result.add "  [key: string]: " & tsType(schema["additionalProperties"]) & ";\n"
    result.add "}\n\n"

proc renderTs*(operations: seq[Operation], schemas: JsonNode = nil): string =
  result = "// Generated by tools/contract-gen. Do not edit.\n\n"
  result.add("export type HttpMethod = \"GET\" | \"POST\" | \"PUT\" | \"PATCH\" | \"DELETE\";\n\n")
  result.add renderTsTypes(schemas)
  result.add("export interface RouteSpec {\n")
  result.add("  operationId: string;\n  httpMethod: HttpMethod;\n  path: string;\n")
  result.add("  tag: string;\n  pathParams: string[];\n  queryParams: string[];\n")
  result.add("  hasBody: boolean;\n  isWebSocket: boolean;\n}\n\n")
  result.add("export const routes: readonly RouteSpec[] = [\n")
  for operation in operations:
    let params = operation.pathParams.mapIt(tsString(it)).join(", ")
    let queries = operation.queryParams.mapIt(tsString(it)).join(", ")
    result.add("  {\n")
    result.add("    operationId: " & tsString(operation.operationId) & ",\n")
    result.add("    httpMethod: " & tsString(operation.httpMethod) & ",\n")
    result.add("    path: " & tsString(operation.path) & ",\n")
    result.add("    tag: " & tsString(operation.tag) & ",\n")
    result.add("    pathParams: [" & params & "],\n")
    result.add("    queryParams: [" & queries & "],\n")
    result.add("    hasBody: " & (if operation.hasBody: "true" else: "false") & ",\n")
    result.add("    isWebSocket: " & (if operation.isWebSocket: "true" else: "false") & ",\n")
    result.add("  },\n")
  result.add("];\n")
