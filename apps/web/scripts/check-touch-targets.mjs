#!/usr/bin/env node
/**
 * The touch gate, in two halves that answer two different questions.
 *
 *   1. Source: every `<button>` in an app and in the `@majadu/*` packages it
 *      renders carries a marker from MARKERS. This half only judges a class
 *      list it can read: a plain `className="..."`, or `className={NAME}` where
 *      NAME is a plain string const in the same file. An expression cannot be
 *      read without a type checker, so those sites are reported as unverified
 *      rather than counted as a pass. `e2e/touch.spec.ts` is the instrument for
 *      them: it measures the rendered box at 360 and 390.
 *
 *   2. Artifact: the built stylesheet decides. Before 2026-11-26 this script
 *      asserted spelling, so 111 `hit44` tokens with no CSS rule anywhere
 *      passed a green gate while 30-34px controls shipped, and
 *      `packages/scoreboard-ui` was never scanned by Tailwind at all because no
 *      `@source` directive covered it. Both facts are now assertions:
 *        - every marker a source uses has a rule in the built CSS;
 *        - every class a `@majadu/*` package renders has a rule in the built
 *          CSS of every app that renders it;
 *        - every such package has an `@source` directive in the app's CSS entry,
 *          because a package that is not scanned compiles to nothing even when
 *          its class names are spelled correctly.
 *
 * Half 2 is why this script runs after a build. `./task check` builds both apps
 * then asserts; `build:web` and `build:scoreboard` assert themselves the way
 * `check-precache.mjs` already does.
 *
 * A class this repository defines by hand instead of through Tailwind is listed
 * in CUSTOM_CLASSES. That list is deliberately short: it is not an exemption
 * mechanism, it exists because `score-face` is a real selector in
 * `apps/scoreboard/src/index.css`.
 *
 *   node scripts/check-touch-targets.mjs             # both apps, needs dist
 *   node scripts/check-touch-targets.mjs --app web   # one app
 *   node scripts/check-touch-targets.mjs --source    # half 1 only, no build
 */
import { existsSync, readdirSync, readFileSync, realpathSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(HERE, '../../..')

/** A control smaller than 44px on purpose opts into one of these. */
const MARKERS = ['min-h-11', 'h-11', 'hit44']

/** `hit44` only works if the pseudo-element that takes the taps is emitted. */
const HIT44_SIZES = ['2.75rem', '44px']

/** Selectors written by hand in an app's CSS rather than generated by Tailwind. */
const CUSTOM_CLASSES = new Set(['score-face'])

const APPS = {
  web: { dir: 'apps/web', css: 'apps/web/src/index.css', dist: 'apps/web/dist/assets' },
  scoreboard: {
    dir: 'apps/scoreboard',
    css: 'apps/scoreboard/src/index.css',
    dist: 'apps/scoreboard/dist/assets',
  },
}

const EXEMPTIONS_FILE = join(HERE, 'touch-target-exemptions.json')

const problems = []
const notes = []
const fail = (message) => {
  console.error(message)
  process.exit(1)
}

const args = process.argv.slice(2)
const sourceOnly = args.includes('--source')
const appArg = args.includes('--app') ? args[args.indexOf('--app') + 1] : null
if (appArg !== null && !(appArg in APPS)) {
  fail(`unknown app '${appArg}' (expected ${Object.keys(APPS).join(' or ')})`)
}
const targetApps = appArg === null ? Object.keys(APPS) : [appArg]

/**
 * `--dist <dir>` reads the stylesheet from somewhere other than the app's build
 * directory. Only `scripts/touch-gate-selftest.mjs` uses it, to prove the gate
 * fails on a mutated copy of the artifact without rebuilding the real tree.
 */
const distArg = args.includes('--dist') ? args[args.indexOf('--dist') + 1] : null
if (distArg !== null && targetApps.length !== 1) fail('--dist needs exactly one --app')

// ── source and artifact helpers ─────────────────────────────────────────────

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === 'dist') continue
    const path = join(dir, entry.name)
    if (entry.isDirectory()) walk(path, out)
    else out.push(path)
  }
  return out
}

const isSource = (file) =>
  /\.(tsx|ts)$/.test(file) && !/\.test\.(tsx|ts)$/.test(file) && !file.includes('__tests__')

/**
 * `packages/` sits outside each app root, so it is enumerated from the app's own
 * dependencies instead of a hard-coded list: a package added tomorrow is
 * covered without editing this file.
 */
function majaduPackages(app) {
  const manifest = JSON.parse(readFileSync(join(REPO_ROOT, APPS[app].dir, 'package.json'), 'utf8'))
  const names = Object.keys(manifest.dependencies ?? {}).filter((name) => name.startsWith('@majadu/'))
  return names.map((name) => {
    const linked = join(REPO_ROOT, APPS[app].dir, 'node_modules', ...name.split('/'))
    if (!existsSync(linked)) fail(`${app}: ${name} is a dependency but is not installed; run pnpm install`)
    const dir = realpathSync(linked)
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
    const entry = typeof pkg.exports === 'string' ? pkg.exports : Object.values(pkg.exports ?? {})[0]
    const src = join(dir, dirname(typeof entry === 'string' ? entry : './src/index.ts'))
    return { name, dir, src }
  })
}

/** Class tokens written as static text. An `${...}` hole is skipped, never guessed. */
function classTokens(root) {
  const tokens = new Set()
  for (const file of walk(root).filter(isSource)) {
    const text = readFileSync(file, 'utf8')
    for (const match of text.matchAll(/className=(?:"([^"]*)"|\{\s*`([^`]*)`\s*\})/g)) {
      const value = (match[1] ?? match[2] ?? '').replace(/\$\{[^}]*\}/g, ' ')
      for (const token of value.split(/\s+/)) {
        if (/^-?[a-zA-Z][a-zA-Z0-9:/.%[\]_-]*$/.test(token)) tokens.add(token)
      }
    }
  }
  return [...tokens]
}

/** Built CSS with Tailwind's escapes removed, so `.bg-white\/8` reads as `.bg-white/8`. */
function builtCss(app) {
  const dir = distArg ?? join(REPO_ROOT, APPS[app].dist)
  if (!existsSync(dir)) fail(`${app}: ${dir} is missing: build it first (./task check does)`)
  const files = readdirSync(dir).filter((name) => name.endsWith('.css'))
  if (files.length === 0) fail(`${app}: ${dir} holds no .css: the build emitted no stylesheet`)
  return files.map((name) => readFileSync(join(dir, name), 'utf8')).join('\n').replace(/\\/g, '')
}

function ruleExists(css, token) {
  const escaped = token.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')
  return new RegExp(`\\.${escaped}(?![\\w-])`).test(css)
}

// ── exemptions: the repository's own convention (owner, expiry, reason) ─────

const exemptions = existsSync(EXEMPTIONS_FILE)
  ? JSON.parse(readFileSync(EXEMPTIONS_FILE, 'utf8'))
  : { buttons: [] }

/**
 * Keyed by the exact `file:line` the gate prints, so an entry is copied from a
 * red run rather than derived. A line that moves is a new red run, which is the
 * point: the exemption is a dated debt, not a permanent allowlist.
 */
function exemptButton(where) {
  const entry = (exemptions.buttons ?? []).find((candidate) => candidate.at === where)
  if (entry === undefined) return false
  if (entry.owner === undefined || entry.expires === undefined || entry.reason === undefined) {
    problems.push(`exemption ${where} needs owner, expires and reason`)
    return false
  }
  if (entry.expires < new Date().toISOString().slice(0, 10)) {
    problems.push(`exemption ${where} expired on ${entry.expires} (owner ${entry.owner}); fix it or move the date`)
    return false
  }
  notes.push(`exempt ${where} until ${entry.expires} (${entry.owner})`)
  return true
}

// ── half 1: every <button> in the app and in the packages it renders ────────

/** Returns the index just past the opening `>` of the tag starting at `start`. */
function tagEnd(text, start) {
  let depth = 0
  let quote = null
  for (let i = start; i < text.length; i += 1) {
    const char = text[i]
    if (quote !== null) {
      if (char === quote && text[i - 1] !== '\\') quote = null
      continue
    }
    if (char === '"' || char === "'" || char === '`') quote = char
    else if (char === '{') depth += 1
    else if (char === '}') depth -= 1
    else if (char === '>' && depth === 0) return i + 1
  }
  return -1
}

const lineOf = (text, index) => text.slice(0, index).split('\n').length

/** `className={CONST}` where CONST is a plain string const in the same file. */
function constValue(text, name) {
  const match = text.match(new RegExp(`(?:const|let)\\s+${name}\\s*=\\s*(['"])([^'"]*)\\1`))
  return match === null ? null : match[2]
}

function scanButtons(app) {
  const roots = [join(REPO_ROOT, APPS[app].dir, 'src'), ...majaduPackages(app).map((pkg) => pkg.src)]
  let unverified = 0
  for (const root of roots) {
    for (const file of walk(root).filter(isSource)) {
      const text = readFileSync(file, 'utf8')
      let cursor = 0
      for (;;) {
        const start = text.indexOf('<button', cursor)
        if (start === -1) break
        const end = tagEnd(text, start + '<button'.length)
        if (end === -1) break
        cursor = end
        const tag = text.slice(start, end)
        const where = `${relative(REPO_ROOT, file)}:${lineOf(text, start)}`
        const literal = tag.match(/className="([^"]*)"/)
        const expression = literal === null ? tag.match(/className=\{([^}]*)\}/) : null

        let value = null
        if (literal !== null) value = literal[1]
        else if (expression !== null && /^[A-Za-z_$][\w$]*$/.test(expression[1].trim())) {
          value = constValue(text, expression[1].trim())
          if (value === null) {
            notes.push(`unverified ${where} (className={${expression[1].trim()}} is not a plain string)`)
            unverified += 1
            continue
          }
        }

        if (value === null) {
          // A template literal or an inline conditional mixes static text with
          // values only the browser knows. Measured by e2e/touch.spec.ts.
          notes.push(`unverified ${where} (className is not static)`)
          unverified += 1
          continue
        }
        if (!MARKERS.some((marker) => value.includes(marker)) && !exemptButton(where)) {
          problems.push(`${where} has no touch marker (wants one of ${MARKERS.join(', ')})`)
        }
      }
    }
  }
  return unverified
}

// ── half 2: the built stylesheet is the one that decides ────────────────────

function assertArtifact(app) {
  const css = builtCss(app)
  const appSrc = join(REPO_ROOT, APPS[app].dir, 'src')
  const packages = majaduPackages(app)

  // A marker a source actually uses must have a rule. One it never uses is not
  // this app's business: the scoreboard does not render `hit44` at all.
  const usedMarkers = new Set(classTokens(appSrc))
  for (const pkg of packages) for (const token of classTokens(pkg.src)) usedMarkers.add(token)
  for (const marker of MARKERS) {
    if (usedMarkers.has(marker) && !ruleExists(css, marker)) {
      problems.push(`${app}: .${marker} is used but has no rule in the built CSS`)
    }
  }

  if (ruleExists(css, 'hit44')) {
    const pseudo = css.match(/\.hit44(?:::?after)[^{]*\{([^}]*)\}/)
    if (pseudo === null) problems.push(`${app}: .hit44 has no ::after rule, so it expands nothing`)
    else if (!HIT44_SIZES.some((size) => /width:\s*(2\.75rem|44px)/.test(pseudo[1]))) {
      problems.push(`${app}: .hit44::after is not 44px wide (${pseudo[1].trim()})`)
    }
  }

  // The shared packages are the ones that compile to nothing when Tailwind does
  // not scan them, so their classes are the ones asserted against this app's
  // build. A dead class in the app's own tree is a dead-CSS finding, not a touch
  // one, and does not fail this gate.
  const entry = readFileSync(join(REPO_ROOT, APPS[app].css), 'utf8')
  const sources = [...entry.matchAll(/@source\s+"([^"]+)"/g)].map((match) =>
    resolve(join(REPO_ROOT, APPS[app].css), '..', match[1]),
  )

  let covered = 0
  for (const pkg of packages) {
    const tokens = classTokens(pkg.src).filter((token) => !CUSTOM_CLASSES.has(token))
    if (tokens.length === 0) continue
    const coveredBySource = sources.some((source) => pkg.src === source || pkg.src.startsWith(`${source}/`))
    if (!coveredBySource) {
      problems.push(
        `${app}: ${pkg.name} renders ${tokens.length} class(es) but ${APPS[app].css} has no @source for ${relative(REPO_ROOT, pkg.src)}`,
      )
      continue
    }
    covered += 1
    // Only a missing rule is a failure. A class inside an expression the build
    // legitimately never emits (a branch that is not taken) is not observable
    // here; the sampled ones below are the ones this package actually renders.
    for (const token of tokens) {
      if (ruleExists(css, token)) continue
      problems.push(`${app}: .${token} is rendered by ${pkg.name} but has no rule in the built CSS`)
    }
  }
  return covered
}

// ── run ────────────────────────────────────────────────────────────────────

for (const app of targetApps) {
  const unverified = scanButtons(app)
  const covered = sourceOnly ? null : assertArtifact(app)
  notes.push(
    `${app}: ${unverified} unverified button(s)` +
      (covered === null ? '' : `, ${covered} package source(s) covered`),
  )
}

if (problems.length > 0) {
  if (notes.length > 0) console.error(notes.join('\n'))
  console.error(problems.join('\n'))
  process.exit(1)
}

console.error(notes.join('\n'))
console.log('touch gate: ok (markers present, and every class a shared package renders has a rule in the built CSS)')
